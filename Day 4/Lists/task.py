fruits = ["Cherry", "Apple", "Pear"]
print(fruits)

# Access single element
print(fruits[1])
print(fruits[-3])

# Modify single element
fruits[2] = "Mango"

# Add element to list
fruits.append("Plum")
print(fruits)

# Add multiple elements to the list
fruits.extend(["Pear", "Banana"])
print(fruits)
